/** Pad a 5x7 glyph into an 8x8 cell (glyph at columns 0-4, rows 0-6). */
export function padGlyph(g: string[]): string[] {
  return [...g.map((r) => r + "..."), "........"];
}

export function fontDefs(): Record<FontName, SpriteDef> {
  const out = {} as Record<FontName, SpriteDef>;
  for (const ch of FONT_CHARS) {
    out[`font_${ch}`] = { cls: "font", palette: { "#": "#f4f0e6" }, frames: [padGlyph(GLYPHS_5X7[ch]!)] };
  }
  return out;
}
